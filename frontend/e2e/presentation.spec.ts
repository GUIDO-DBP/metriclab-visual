import {test,expect} from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'
const root=path.resolve('..'), read=(p:string)=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'))
const manifest=read('runtime/data/manifest.json')
const hsv='hsv128-edge16-v1',resnet='torchvision-resnet18-imagenet1k-v1-avgpool512-fp32'

test('interpretación por descriptor, resúmenes de matrices reales y móvil sin desbordamiento',async({page})=>{
  test.setTimeout(120000)
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button',{name:'Comparación de clasificadores',exact:true}).click()
  for(const descriptor of [hsv,resnet]) {
    await page.getByLabel('Descriptor visual').selectOption(descriptor)
    await expect(page.locator('.historical-context')).toContainText('Este conjunto ya se utilizó')
    await page.getByText('Consultar explicación metodológica',{exact:true}).click()
    await expect(page.locator('.historical-context details')).toHaveAttribute('open','')
    const interpretation=page.getByRole('region',{name:'Interpretación de resultados'})
    await expect(interpretation).toContainText('No es una prueba estadística')
    await expect(interpretation.locator('.interpretation-grid>div').first()).toContainText(descriptor===resnet?'LightGBM':'XGBoost')
    await expect(interpretation.locator('.interpretation-grid>div').nth(1)).toContainText('XGBoost')
    await page.getByLabel('Modelo evaluado').selectOption('lightgbm')
    const response=await page.request.get('/api/experiments?descriptor_id='+descriptor)
    const data=await response.json(),m=data.metrics.find((r:{key:string})=>r.key==='lightgbm')
    const expected=data.classes.map((name:string,i:number)=>{
      const support=m.confusion[i].reduce((a:number,b:number)=>a+b,0)
      return {name,recall:m.confusion[i][i]/support,support,correct:m.confusion[i][i]}
    }).sort((a:{recall:number;name:string},b:{recall:number;name:string})=>a.recall-b.recall||a.name.localeCompare(b.name)).slice(0,5)
    const low=page.getByRole('region',{name:'Cinco categorías con menor recall'})
    await expect(low.locator('tbody tr')).toHaveCount(5)
    for(let i=0;i<5;i++) {
      const row=low.locator('tbody tr').nth(i)
      await expect(row.locator('th')).toHaveText(expected[i].name.replaceAll('_',' '))
      await expect(row.locator('td').last()).toHaveText(`${expected[i].correct} / ${expected[i].support}`)
    }
    await expect(page.getByRole('table',{name:'Matriz de confusión'}).locator('tbody tr')).toHaveCount(101)
    const before=await low.innerText()
    await page.getByLabel('Filtrar categorías').fill('accordion')
    await expect(page.getByRole('table',{name:'Matriz de confusión'}).locator('tbody tr')).toHaveCount(1)
    expect(await low.innerText()).toBe(before)
    await page.getByLabel('Filtrar categorías').fill('')
    await page.setViewportSize({width:390,height:844})
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
    const scroll=page.getByRole('region',{name:'Desplazamiento de la matriz completa'})
    await scroll.focus();await scroll.press('ArrowRight')
    await expect.poll(()=>scroll.evaluate(e=>e.scrollLeft)).toBeGreaterThan(0)
    await page.screenshot({path:`../runtime/ui_improvements/evaluation-${descriptor===hsv?'hsv':'resnet'}-mobile.png`,fullPage:true})
    await page.setViewportSize({width:1440,height:1000})
  }
  await page.screenshot({path:'../runtime/ui_improvements/evaluation-desktop.png',fullPage:true})
  expect(errors).toEqual([])
})

test('verdad conocida solo al elegir muestra identificada; se borra al subir archivo externo',async({page})=>{
  test.setTimeout(120000)
  await page.goto('/')
  await page.locator('.hero-cta').click()
  await page.getByLabel('Muestra identificada del conjunto de prueba').waitFor()
  await page.setViewportSize({width:390,height:844})
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  const dataset=await(await page.request.get('/api/dataset')).json()
  const sample=dataset.samples.find((s:{category:string})=>s.category==='accordion')
  expect(sample).toBeTruthy()
  const truth=sample.category.replaceAll('_',' ')
  await page.getByLabel('Muestra identificada del conjunto de prueba').selectOption(String(sample.id))
  await page.setViewportSize({width:1440,height:1000})
  await page.getByLabel('Modelo de clasificación').selectOption('xgboost')
  const response=page.waitForResponse(r=>r.url().endsWith('/api/classify')&&r.request().method()==='POST')
  await page.locator('.classification-config .primary').click()
  const prediction=(await(await response).json()).predictions[0].category.replaceAll('_',' ')
  await expect(page.getByTestId('ground-truth')).toContainText(`Categoría verdadera: ${truth}`)
  await expect(page.getByTestId('ground-truth')).toContainText(truth===prediction?'El modelo acertó':'El modelo no acertó')
  await page.getByLabel('Descriptor visual').selectOption(resnet)
  await page.locator('.classification-config .primary').click()
  await expect(page.getByTestId('ground-truth')).toContainText(`Categoría verdadera: ${truth}`,{timeout:60000})
  await expect(page.locator('.category-gallery .image-card')).toHaveCount(6)
  await page.screenshot({path:'../runtime/ui_improvements/known-sample.png',fullPage:true})
  await page.getByLabel('Modelo de clasificación').selectOption('decision_tree')
  await expect(page.locator('.classification-config .primary')).toBeEnabled()
  const entropyResponse=page.waitForResponse(r=>r.url().endsWith('/api/classify')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'Entropía',exact:true}).click()
  const entropyPrediction=(await(await entropyResponse).json()).predictions[0].category.replaceAll('_',' ')
  expect(entropyPrediction).not.toBe(truth)
  await expect(page.getByTestId('ground-truth')).toContainText('El modelo no acertó en esta muestra.')
  await expect(page.locator('.category-gallery .image-card').first()).toHaveAttribute('data-category',entropyPrediction.replaceAll(' ','_'))
  const raw=fs.readFileSync(path.join(root,manifest.query[0].path))
  await page.locator('input[type=file]').setInputFiles({name:'accordion.jpg',mimeType:'image/jpeg',buffer:raw})
  await page.locator('.classification-config .primary').click()
  await expect(page.getByTestId('ground-truth')).toContainText('Categoría verdadera desconocida')
  await expect(page.getByTestId('ground-truth')).not.toContainText('Categoría verdadera:')
})

test('explorador educativo y rechazo de ruta tardía de otro descriptor',async({page})=>{
  await page.goto('/')
  await page.locator('.hero-cta').click()
  await page.locator('input[type=file]').setInputFiles(path.join(root,manifest.query[0].path))
  await page.getByRole('button',{name:'Explorador de árboles',exact:true}).click()
  await expect(page.getByTestId('node-explanation')).toContainText('Nodo raíz')
  await page.getByText('Cómo leer un árbol de decisión',{exact:true}).click()
  await expect(page.locator('.tree-reading-guide')).toContainText('rama izquierda')
  let release:()=>void=()=>{}
  const gate=new Promise<void>(resolve=>{release=resolve})
  await page.route('**/api/models/gini/path',async route=>{
    const response=await route.fetch();await gate;await route.fulfill({response})
  })
  const requested=page.waitForRequest(r=>r.url().endsWith('/api/models/gini/path'))
  await page.getByRole('button',{name:'Ver ruta de imagen cargada',exact:true}).click()
  await requested
  await page.getByLabel('Descriptor visual').selectOption(resnet)
  await expect(page.getByTestId('node-explanation')).toContainText('componente numérico del embedding')
  release()
  await expect(page.getByLabel('Paso de la ruta de clasificación')).toHaveCount(0)
  await page.screenshot({path:'../runtime/ui_improvements/tree-guide.png',fullPage:true})
})
