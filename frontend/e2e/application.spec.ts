import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve('..')
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'runtime/data/manifest.json'), 'utf8'))
const sample = path.join(root, manifest.query[0].path)

test('flujo real: búsqueda, ampliación, clasificación, laboratorio y dataset', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('4 clasificadores disponibles')).toBeVisible()
  await page.screenshot({ path: '../runtime/home-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Laboratorio de búsqueda métrica — Trabajo complementario', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles(sample)
  await page.getByRole('button', { name: 'Buscar imágenes similares', exact: true }).click()
  await expect(page.locator('.image-card')).toHaveCount(10)
  await expect(page.getByText('Verificado con secuencial')).toBeVisible()
  await page.locator('.image-card').first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({ path: '../runtime/search-desktop.png', fullPage: true })
  await page.getByRole('navigation').getByRole('button', { name: 'Clasificar imagen', exact: true }).click()
  await page.getByRole('button', { name: 'Comparar los cuatro modelos', exact: true }).click()
  await expect(page.getByRole('table', {name:'Comparación de predicciones'}).locator('tbody tr')).toHaveCount(4)
  await page.getByRole('button', { name: 'Laboratorio de búsqueda métrica — Trabajo complementario', exact: true }).click()
  await page.getByRole('button', { name: 'Comparar índices', exact: true }).click()
  await page.getByRole('button', { name: 'Comparar los tres índices' }).click()
  await expect(page.getByText('3 índices verificados')).toBeVisible()
  await expect(page.getByLabel('Paso de la traza')).toBeVisible()
  await page.getByLabel('Paso siguiente').click()
  await expect(page.getByText('Distancia calculada · nodo 0')).toBeVisible()
  await page.screenshot({ path: '../runtime/lab-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Dataset y metodología', exact: true }).click()
  await expect(page.locator('.distribution-table tbody tr')).toHaveCount(101)
  await expect(page.getByText('Dataset académico real')).toBeVisible()
  expect(errors).toEqual([])
})

test('móvil: navegación y carga accesibles sin desbordamiento horizontal', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByText('4 clasificadores disponibles')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../runtime/home-mobile.png', fullPage: true })
  await page.locator('.hero-cta').click()
  await page.locator('input[type=file]').setInputFiles(sample)
  await page.locator('.classification-config .primary').click()
  await expect(page.locator('.prediction')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../runtime/classification-mobile.png', fullPage: true })
  await page.getByRole('button', {name:'Comparar los cuatro modelos',exact:true}).click()
  await expect(page.getByRole('table',{name:'Comparación de predicciones'}).locator('tbody tr')).toHaveCount(4)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  for (const name of ['Comparación de clasificadores','Explorador de árboles','Dataset y metodología']) {
    await page.getByRole('navigation').getByRole('button',{name,exact:true}).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})
