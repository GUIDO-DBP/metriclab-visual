import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve('..')
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'runtime/data/manifest.json'), 'utf8'))
const sample = path.join(root, manifest.query[0].path)

test('flujo real: búsqueda, ampliación, clasificación, laboratorio y dataset', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('Motor C++ conectado')).toBeVisible()
  await page.screenshot({ path: '../runtime/home-desktop.png', fullPage: true })
  await page.getByRole('button', { name: /Buscar imágenes similares/ }).click()
  await page.locator('input[type=file]').setInputFiles(sample)
  await page.getByRole('button', { name: 'Buscar imágenes similares', exact: true }).click()
  await expect(page.locator('.image-card')).toHaveCount(10)
  await expect(page.getByText('Verificado con secuencial')).toBeVisible()
  await page.locator('.image-card').first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({ path: '../runtime/search-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Clasificación', exact: true }).click()
  await page.getByRole('button', { name: 'Comparar modelos', exact: true }).click()
  await expect(page.locator('.prediction')).toHaveCount(4)
  await expect(page.getByText('Hoja →', { exact: false }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Laboratorio', exact: true }).click()
  await page.getByRole('button', { name: 'Comparar los tres índices' }).click()
  await expect(page.getByText('3 índices verificados')).toBeVisible()
  await expect(page.getByLabel('Paso de la traza')).toBeVisible()
  await page.getByLabel('Paso siguiente').click()
  await expect(page.getByText('Distancia calculada · nodo 0')).toBeVisible()
  await page.screenshot({ path: '../runtime/lab-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Dataset y proyecto', exact: true }).click()
  await expect(page.locator('.category-list>div')).toHaveCount(101)
  await expect(page.getByText('Datos de Caltech-101 local')).toBeVisible()
  expect(errors).toEqual([])
})

test('móvil: navegación y carga accesibles sin desbordamiento horizontal', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByText('Motor C++ conectado')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../runtime/home-mobile.png', fullPage: true })
  await page.getByRole('button', { name: /Buscar imágenes similares/ }).click()
  await page.locator('input[type=file]').setInputFiles(sample)
  await page.getByRole('button', { name: 'Buscar imágenes similares', exact: true }).click()
  await expect(page.locator('.image-card')).toHaveCount(10)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../runtime/search-mobile.png', fullPage: true })
})
