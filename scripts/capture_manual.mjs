import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
const root=path.resolve(import.meta.dirname,'..')
const require=createRequire(path.join(root,'frontend/package.json'))
const {chromium}=require('@playwright/test')
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1})
const base=process.env.METRICLAB_CAPTURE_URL || 'http://127.0.0.1:8000'
const out=path.join(root,'documentacion_entrega/assets')
const errors=[];page.on('pageerror',e=>errors.push(e.message))
try {
  await page.goto(base)
  await page.getByText('4 clasificadores disponibles').waitFor()
  await page.screenshot({path:path.join(out,'08_inicio.png')})
  await page.getByLabel('Descriptor visual').selectOption('torchvision-resnet18-imagenet1k-v1-avgpool512-fp32')
  await page.locator('.hero-cta').click()
  const manifest=JSON.parse(fs.readFileSync(path.join(root,'runtime/data/manifest.json'),'utf8'))
  await page.locator('input[type=file]').setInputFiles(path.join(root,manifest.query[0].path))
  await page.getByLabel('Modelo de clasificación').selectOption('lightgbm')
  await page.locator('.classification-config .primary').click()
  await page.locator('.category-gallery .image-card').first().waitFor({timeout:90000})
  await page.locator('.classification-config').screenshot({path:path.join(out,'08_modelos.png')})
  await page.locator('.category-examples').screenshot({path:path.join(out,'08_galeria.png')})
  await page.getByRole('button',{name:'Comparar los cuatro modelos',exact:true}).click()
  await page.getByRole('table',{name:'Comparación de predicciones'}).waitFor()
  await page.locator('.same-image-comparison').screenshot({path:path.join(out,'08_comparacion.png')})
  await page.getByRole('button',{name:'Explorador de árboles',exact:true}).click()
  await page.locator('.classifier-tree svg').waitFor()
  await page.locator('.classifier-tree').screenshot({path:path.join(out,'08_arbol.png')})
  await page.getByLabel('Algoritmo del explorador').selectOption('lightgbm')
  await page.locator('.boosting-explanation').waitFor()
  await page.screenshot({path:path.join(out,'08_importancia.png')})
  await page.getByRole('button',{name:'Comparación de clasificadores',exact:true}).click()
  await page.locator('.evaluation-table tbody tr').first().waitFor()
  await page.screenshot({path:path.join(out,'08_evaluacion.png')})
  await page.getByRole('button',{name:'Dataset y metodología',exact:true}).click()
  await page.locator('.distribution-table').waitFor()
  await page.screenshot({path:path.join(out,'08_dataset.png')})
  if(errors.length) throw Error(errors.join('\n'))
  console.log('8 capturas reales generadas sin errores JavaScript.')
} finally {await browser.close()}
